/**
 * Regenerates src/generated/deployKit.ts from the compiled BountyEscrow artifact and its flattened source.
 *
 *   forge build && forge flatten contracts/BountyEscrow.sol -o /tmp/BountyEscrow.flat.sol
 *   bun run scripts/gen-deploy-kit.ts /tmp/BountyEscrow.flat.sol
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { keccak256 } from 'viem'
import type { Hex } from 'viem'

const flatPath = process.argv[2]
if (!flatPath) throw new Error('Pass the flattened source path as the first argument')

const artifact = JSON.parse(readFileSync('contracts/out/BountyEscrow.sol/BountyEscrow.json', 'utf8')) as {
  bytecode: { object: string }
  metadata: {
    compiler: { version: string }
    settings: { optimizer: { enabled: boolean; runs: number }; evmVersion: string }
  }
}

const bytecode = artifact.bytecode.object as Hex
if (!/^0x[0-9a-f]+$/.test(bytecode) || bytecode.length % 2 !== 0) throw new Error('Artifact bytecode is not complete hex')

// The last two bytes hold the length of the CBOR metadata block appended by solc.
const metadataBytes = parseInt(bytecode.slice(-4), 16) + 2
const withoutMetadata = bytecode.slice(0, bytecode.length - metadataBytes * 2) as Hex

const kit = {
  bytecode,
  bytecodeHash: keccak256(bytecode),
  metadataBytes,
  withoutMetadataHash: keccak256(withoutMetadata),
  compiler: artifact.metadata.compiler.version,
  optimizerEnabled: artifact.metadata.settings.optimizer.enabled,
  optimizerRuns: artifact.metadata.settings.optimizer.runs,
  evmVersion: artifact.metadata.settings.evmVersion,
  flattenedSource: readFileSync(flatPath, 'utf8'),
}

mkdirSync('src/generated', { recursive: true })
writeFileSync(
  'src/generated/deployKit.ts',
  `// GENERATED by scripts/gen-deploy-kit.ts. Do not edit by hand.\nexport const deployKit = ${JSON.stringify(kit, null, 2)} as const\n`,
)
console.log(`bytes=${(bytecode.length - 2) / 2} hash=${kit.bytecodeHash} metadata=${metadataBytes}`)
